print("\n---Задание 4: График погрешности для x=5---")
x_fixed = 5  # фиксированное значени х
exact_val = math.exp(x_fixed)  # точное значение е^5
terms_list = []
errors_list = []

term = 1.0
s = 1.0
n = 1
while n < 50:
    term *= x_fixed / n
    s += term
    n += 1
    terms_list.append(n - 1)  # сохраняем номер члена
    errors_list.append(abs(exact_val - s))  # сохраняем ошибку

plt.figure(figsize=(8, 5))
plt.semilogy(terms_list, errors_list, "o-", color="red")  # строит
# график с логарифмической шкалой по вертикали,
# чтобы увидеть экспоненциальное убывание ошибка
plt.title("Погрешность частичных сумм для 1/(1+x)")
plt.xlabel("Число членов")
plt.ylabel("Абсолютна погрешность (лог. шкала)")
plt.grid(True, which="both", linestyle="--")  # добавляет сетку для удобства
plt.show()  # отображает график
