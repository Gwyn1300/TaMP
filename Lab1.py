def machine_epsilon(dtype):  # функция, котрая определяет машинный эпсилон
    # для заданного типа (np.float64(x) или np.float32(x))
    eps = 1.0  # начальное значение
    while dtype(1.0 + eps) != dtype(1.0):  # пока 1 + eps отличается
        # от 1(компьютер видит разницу), делим esp поплам
        eps /= 2.0
    return eps * 2.0  # возвращаем последнее значение, при котором разница


