# ==================================================
# ЗАДАНИЕ 1: Сравнение точности float64 и float32
# ==================================================


def func(x):  # объявление функции, котрая вычисляет (1-cos(x))/sin(x)
    if abs(x) < 1e-300:  # если х обчень близок к нулю,
        # возвращаем1(передел функции), чтобы избежать деления на ноль
        return 1.0
    return (1 - np.cos(x)) / np.sin(x)  # основное вычисление


x_vals = np.logspace(-1, -15, 15)  # создает массив из 15 чисел
# от 10^-1 до 10^-15 для тестирования

print("\n--- Задание 1: Сравнение точности float64 и float32 --- ")
print(f"{'x':<10} {'float64':<20} {'float32':<20} {'Отн. ошибка': <15}")
print("-" * 65)

for x in x_vals:
    res64 = func(np.float64(x))  # вычисление в двойной точности(эталон)
    res32 = func(np.float32(x))  # вычисление в одинарной точности
    if res64 != 0:
        rel_err = abs(res64 - res32) / abs(res64)  # отностительная погрешность
    else:
        rel_err = 0
    print(f"{x:<10.1e} {res64:<20.10f} {res32:<20.10f} {rel_err:<15.2e}")

