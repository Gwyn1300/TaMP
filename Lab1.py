def my_f(x):  # функция вычисления 1/(1+х) через ряд Тейлора
    term = 1.0  # первый член ряда
    s = 1.0  # сумма, начинается с первого члена
    n = 1  # номер следующего члена (начинаем с 1, так как 0-й уже учтен)
    while abs(term) > eps:  # пока член больше заданной точности
        term *= -x  # рекуррентная формула для следующего члена
        s += term  # добавляем член к сумме
        n += 1  # увеличиваем номер члена
    return s, n - 1  # возвращаем сумму и количество членов (включая нулевой).


# в цикле проверяются значения х = 1, -1, 10 с разной точностью.


print("\n--- Задание 3: Ряд Тейлора для 1/(1+x)---")
for x in [
    0.5,
    -0.5,
    0.9,
]:
    for eps in [1e-6, 1e-10]:
        approx, terms = my_f(x)
        exact = 1 / (1 + x)
        print(
            f"x = {x:3}, eps={eps:.0e}: approx={approx:.10f}"
            f"exact={exact:.10f}, terms={terms}, error = {abs(approx - exact):.2e}"
        )

